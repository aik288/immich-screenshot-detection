"""
Async Immich API client built directly on the Immich REST API.

The previous implementation imported ``immich_python_sdk``, a package that is
never installed or generated by this project.  This module talks to the API
documented in ``immich-openapi-specs.json`` using ``aiohttp`` instead.
"""

import logging
from typing import Any, Dict, List, Optional

import aiohttp

logger = logging.getLogger(__name__)


class ImmichAPIError(RuntimeError):
    """Raised when the Immich API returns an error response."""


class ImmichClient:
    """Client for interacting with the Immich REST API."""

    def __init__(self, config):
        self.config = config
        self.base_url = config.immich_server_url.rstrip("/")
        self.api_key = config.immich_api_key
        self._session: Optional[aiohttp.ClientSession] = None
        self._tag_id: Optional[str] = None

    async def __aenter__(self):
        await self.initialize()
        return self

    async def __aexit__(self, exc_type, exc, tb):
        await self.close()

    async def initialize(self):
        """Create the HTTP session and verify the server is reachable."""
        if self._session is None:
            timeout = aiohttp.ClientTimeout(total=300)
            self._session = aiohttp.ClientSession(
                headers={
                    "x-api-key": self.api_key,
                    "Accept": "application/json",
                },
                timeout=timeout,
            )

        try:
            await self._ping()
            self._tag_id = await self._ensure_tag(self.config.screenshot_tag)
            logger.info("Successfully initialized Immich client")
        except Exception as exc:
            await self.close()
            logger.error("Failed to initialize Immich client: %s", exc)
            raise

    async def close(self):
        """Close the underlying HTTP session."""
        if self._session is not None:
            await self._session.close()
            self._session = None

    async def _request(
        self,
        method: str,
        path: str,
        *,
        json: Optional[Dict[str, Any]] = None,
        expect_json: bool = True,
    ) -> Any:
        """Perform an authenticated request against the Immich API."""
        if self._session is None:
            raise RuntimeError("Immich client is not initialized")

        url = f"{self.base_url}{path}"
        async with self._session.request(method, url, json=json) as response:
            if response.status >= 400:
                body = await response.text()
                raise ImmichAPIError(
                    f"{method} {path} failed with HTTP {response.status}: "
                    f"{body[:500]}"
                )

            if not expect_json or response.status == 204:
                return None
            return await response.json()

    async def _ping(self):
        """Ping the server to verify connectivity and credentials."""
        result = await self._request("GET", "/server/ping")
        if not result or result.get("res") != "pong":
            raise ConnectionError(f"Unexpected ping response: {result!r}")
        logger.debug("Immich server ping succeeded")

    async def _ensure_tag(self, tag_name: str) -> str:
        """Return the id of ``tag_name``, creating the tag if necessary."""
        tags = await self._request("GET", "/tags") or []
        for tag in tags:
            if tag.get("name") == tag_name:
                logger.debug("Using existing tag '%s' (%s)", tag_name, tag["id"])
                return tag["id"]

        created = await self._request("POST", "/tags", json={"name": tag_name})
        logger.info("Created tag '%s'", tag_name)
        return created["id"]

    async def get_all_photos(self) -> List[Dict[str, Any]]:
        """Get every image asset visible to the API key."""
        photos: List[Dict[str, Any]] = []
        page = 1
        page_size = 1000

        while True:
            payload = {"page": page, "size": page_size, "type": "IMAGE"}

            try:
                response = await self._request(
                    "POST", "/search/metadata", json=payload
                )
            except ImmichAPIError as exc:
                logger.error("Error retrieving photos on page %s: %s", page, exc)
                break

            assets = (response or {}).get("assets") or {}
            items = assets.get("items") or []
            photos.extend(items)
            logger.info("Retrieved %s photos from page %s", len(items), page)

            next_page = assets.get("nextPage")
            if not items or not next_page:
                break

            try:
                page = int(next_page)
            except (TypeError, ValueError):
                page += 1

        logger.info("Retrieved total of %s photos", len(photos))
        return photos

    async def download_photo(self, asset_id: str) -> bytes:
        """Download the original bytes for an asset."""
        if self._session is None:
            raise RuntimeError("Immich client is not initialized")

        url = f"{self.base_url}/assets/{asset_id}/original"
        try:
            async with self._session.get(url) as response:
                if response.status >= 400:
                    body = await response.text()
                    raise ImmichAPIError(
                        f"GET /assets/{asset_id}/original failed with HTTP "
                        f"{response.status}: {body[:500]}"
                    )
                return await response.read()
        except Exception as exc:
            logger.error("Error downloading photo %s: %s", asset_id, exc)
            return b""

    async def tag_photo_as_screenshot(self, asset_id: str) -> bool:
        """Apply the configured screenshot tag to an asset."""
        if self._tag_id is None:
            self._tag_id = await self._ensure_tag(self.config.screenshot_tag)

        try:
            result = await self._request(
                "PUT",
                f"/tags/{self._tag_id}/assets",
                json={"ids": [asset_id]},
            )
        except ImmichAPIError as exc:
            logger.error("Error tagging photo %s: %s", asset_id, exc)
            return False

        tagged = bool(result) and all(item.get("success") for item in result)
        if tagged:
            logger.debug("Tagged photo %s as screenshot", asset_id)
        else:
            logger.error("Failed to tag photo %s: %s", asset_id, result)
        return tagged

    async def create_screenshot_album(self, asset_ids: List[str]) -> bool:
        """Add the given assets to the screenshot album, creating it if needed."""
        if not self.config.create_album or not asset_ids:
            return True

        try:
            albums = await self._request("GET", "/albums") or []
            existing = next(
                (
                    album
                    for album in albums
                    if album.get("albumName") == self.config.album_name
                ),
                None,
            )

            if existing:
                await self._request(
                    "PUT",
                    f"/albums/{existing['id']}/assets",
                    json={"ids": asset_ids},
                )
                logger.info(
                    "Added %s assets to existing album '%s'",
                    len(asset_ids),
                    self.config.album_name,
                )
            else:
                await self._request(
                    "POST",
                    "/albums",
                    json={
                        "albumName": self.config.album_name,
                        "description": "Screenshots detected automatically",
                        "assetIds": asset_ids,
                    },
                )
                logger.info(
                    "Created album '%s' with %s assets",
                    self.config.album_name,
                    len(asset_ids),
                )
            return True

        except ImmichAPIError as exc:
            logger.error("Error creating screenshot album: %s", exc)
            return False
